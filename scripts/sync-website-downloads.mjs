import assert from "node:assert/strict";
import { copyFile, readFile, writeFile } from "node:fs/promises";
await copyFile(new URL("./release-downloads.mjs", import.meta.url), new URL("../website/public/downloads.mjs", import.meta.url));
await copyFile(new URL("../update-service/website-release.mjs", import.meta.url), new URL("../website/public/release-feed.mjs", import.meta.url));
const appPath = new URL("../website/public/app.js", import.meta.url);
let app = await readFile(appPath, "utf8");
const start = app.indexOf("/* Latest release "), choices = app.indexOf("const osChoice =", start);
const watchStart = app.indexOf("updateDownloads(true);", choices) + "updateDownloads(true);".length;
const watchEnd = app.indexOf("/* Scroll progress ", watchStart);
assert.ok(start >= 0 && choices > start && watchStart > choices && watchEnd > watchStart, "Website release section markers changed; review before syncing.");
const watcher = `\nwatchRelease(value => {\n  release = value;\n  for (const node of document.querySelectorAll("[data-release-version]")) node.textContent = release.tag_name;\n  updateDownloads();\n});\n\n`;
app = app.slice(0, start) + "/* Latest release --------------------------------------------------------- */\n\n" + app.slice(choices, watchStart) + watcher + app.slice(watchEnd);
if (!app.includes('import { watchRelease } from "./release-feed.mjs";')) app = 'import { watchRelease } from "./release-feed.mjs";\n' + app;
await writeFile(appPath, app);
const headersPath = new URL("../website/public/_headers", import.meta.url);
const headers = await readFile(headersPath, "utf8");
await writeFile(headersPath, headers.replace("connect-src https://api.github.com", "connect-src 'self'"));
const config = JSON.parse(await readFile(new URL("../update-service/wrangler.jsonc", import.meta.url), "utf8"));
config.$schema = "./node_modules/wrangler/config-schema.json";
config.main = "../update-service/worker.mjs";
config.assets.directory = "./public";
await writeFile(new URL("../website/wrangler.jsonc", import.meta.url), JSON.stringify(config, null, 2) + "\n");
console.log("Synced tested download selection, live release feed and API Worker configuration into the separately hosted website.");
