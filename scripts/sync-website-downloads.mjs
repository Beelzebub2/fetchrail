import { copyFile, readFile, writeFile } from "node:fs/promises";
await copyFile(new URL("./release-downloads.mjs", import.meta.url), new URL("../website/public/downloads.mjs", import.meta.url));
await copyFile(new URL("../update-service/website-release.mjs", import.meta.url), new URL("../website/public/release-feed.mjs", import.meta.url));
const headersPath = new URL("../website/public/_headers", import.meta.url);
const headers = await readFile(headersPath, "utf8");
await writeFile(headersPath, headers.replace("connect-src https://api.github.com", "connect-src 'self'"));
const config = JSON.parse(await readFile(new URL("../update-service/wrangler.jsonc", import.meta.url), "utf8"));
config.$schema = "./node_modules/wrangler/config-schema.json";
config.main = "../update-service/worker.mjs";
config.assets.directory = "./public";
await writeFile(new URL("../website/wrangler.jsonc", import.meta.url), JSON.stringify(config, null, 2) + "\n");
console.log("Synced tested download selection, live release feed and Worker configuration into the website.");
